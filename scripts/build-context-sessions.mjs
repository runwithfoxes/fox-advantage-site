#!/usr/bin/env node
/**
 * ⭐ MODULE 1, ITEM 02: THE TWO RECORDINGS, GENERATED FROM THE SAVED REPLIES.
 *
 * Paul, 20 Sep 2026: "Can we give a report that they can download and then try two different
 * prompts and also show them what we get... one with context, one without."
 *
 * The two replies are real runs, saved word for word in
 *   course-files/module-1/context/without-context.md
 *   course-files/module-1/context/with-context.md
 * with the prompt that produced each beside it (`*.prompt.txt`). This script reads them and
 * writes src/app/course/contextSessions.generated.ts, which the page plays.
 *
 * ⛔ NEVER EDIT THE GENERATED FILE, and never tidy a saved reply. To re-record, run the prompt
 * again, save what came back, and run this. Same rule as writerSession.ts: a dramatisation
 * that flatters the lesson is the one version that can embarrass us.
 *
 * It reads a small part of markdown and nothing else: paragraphs, `#` headings, tables,
 * `-` and `1.` lists, and `---` rules (dropped). `**bold**` and `*italic*` are left in the text
 * for the window to draw, and an escaped `\\*` becomes the look-alike U+2217 so it is not read as one. ⛔ It fails loudly on a line it does not understand rather than dropping it.
 *
 * Run: node scripts/build-context-sessions.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "course-files/module-1/context");

const cells = (line) =>
  line
    .trim()
    .replace(/^\|/, "")
    .replace(/\|$/, "")
    .split("|")
    .map((c) => c.trim().replace(/\\\*/g, "\u2217"));

function toBlocks(md, name) {
  const lines = md.replace(/\r/g, "").split("\n");
  const blocks = [];
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    if (!line.trim() || /^-{3,}$/.test(line.trim())) {
      i++;
      continue;
    }
    if (/^\|/.test(line)) {
      const rows = [];
      while (i < lines.length && /^\|/.test(lines[i])) rows.push(lines[i++]);
      if (rows.length < 2 || !/^[\s|:-]+$/.test(rows[1]))
        throw new Error(`${name}: a table with no divider row near "${rows[0]}"`);
      const head = cells(rows[0]);
      blocks.push({
        kind: "table",
        head: head.every((c) => c === "") ? [] : head,
        /* `---:` in the divider row means the reply asked for that column right-aligned. */
        align: cells(rows[1]).map((c) => (/:$/.test(c) ? "r" : "l")),
        rows: rows.slice(2).map(cells),
      });
      continue;
    }
    if (/^(-|\d+\.)\s+/.test(line)) {
      const ordered = /^\d+\./.test(line);
      const items = [];
      while (i < lines.length && /^(-|\d+\.)\s+/.test(lines[i]))
        items.push(lines[i++].replace(/^(-|\d+\.)\s+/, "").trim());
      blocks.push({ kind: "list", ordered, items });
      continue;
    }
    if (/^#{1,6}\s+/.test(line)) {
      /* A heading is a bold paragraph here. The window has one size of type for a reply. */
      blocks.push({ kind: "md", text: `**${line.replace(/^#{1,6}\s+/, "").trim()}**` });
      i++;
      continue;
    }
    if (/^[>`]/.test(line)) throw new Error(`${name}: a line this script does not read: "${line}"`);
    const para = [];
    while (
      i < lines.length &&
      lines[i].trim() &&
      !/^(\||-{3,}$|#{1,6}\s|(-|\d+\.)\s)/.test(lines[i])
    )
      para.push(lines[i++].trim());
    blocks.push({ kind: "md", text: para.join(" ").replace(/\\\*/g, "\u2217").replace(/`/g, "") });
  }
  return blocks;
}

const out = [
  "/* ⛔ GENERATED by scripts/build-context-sessions.mjs from the saved replies in",
  "   course-files/module-1/context/. Do not edit: re-run the script. */",
  'import type { Turn } from "./writerSession";',
  "",
];
for (const [constName, base] of [
  ["CONTEXT_WITHOUT_SESSION", "without-context"],
  ["CONTEXT_WITH_SESSION", "with-context"],
]) {
  const prompt = readFileSync(path.join(dir, `${base}.prompt.txt`), "utf8").trim();
  const reply = readFileSync(path.join(dir, `${base}.md`), "utf8");
  const blocks = toBlocks(reply, base);
  if (blocks.length === 0) throw new Error(`${base}: no blocks came out of the reply`);
  /* Every word of the reply must survive into the blocks. Compare letters and digits only,
     so markdown punctuation that was dropped on purpose does not count. */
  const bare = (s) => s.replace(/[^\p{L}\p{N}€%]/gu, "");
  const flat = blocks
    .map((b) =>
      b.kind === "md"
        ? b.text
        : b.kind === "list"
          ? b.items.join("")
          : [...b.head, ...b.rows.flat()].join(""),
    )
    .join("");
  const want = bare(reply.replace(/^\d+\.\s/gm, ""));
  if (bare(flat) !== want)
    throw new Error(`${base}: the blocks do not carry every word of the saved reply`);
  const turns = [
    { who: "you", text: prompt },
    { who: "writer", blocks },
  ];
  out.push(`export const ${constName}: Turn[] = ${JSON.stringify(turns, null, 2)};`, "");
  console.log(`${base}: ${blocks.length} blocks, ${reply.split(/\s+/).length} words`);
}
writeFileSync(path.join(root, "src/app/course/contextSessions.generated.ts"), out.join("\n"));
console.log("wrote src/app/course/contextSessions.generated.ts");
